-- Dedicated experimental database, trusted superuser only.
CREATE SCHEMA branch_native;
REVOKE ALL ON SCHEMA branch_native FROM PUBLIC;
CREATE TABLE branch_native.branches (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    cutoff bigint NOT NULL
);
CREATE SEQUENCE branch_native.version_ids;
CREATE TABLE branch_native.versions (
    id bigint PRIMARY KEY,
    root_id bigint NOT NULL,
    predecessor bigint NOT NULL,
    branch bigint NOT NULL REFERENCES branch_native.branches(id),
    relid oid NOT NULL,
    generation bigint NOT NULL,
    block bigint NOT NULL,
    offset_no bigint NOT NULL,
    deleted boolean NOT NULL
);
CREATE INDEX versions_root ON branch_native.versions(relid,generation,root_id,id);
CREATE UNIQUE INDEX versions_tid ON branch_native.versions(relid,generation,block,offset_no) WHERE NOT deleted;
REVOKE ALL ON ALL TABLES IN SCHEMA branch_native FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA branch_native FROM PUBLIC;
REVOKE ALL ON FUNCTION pg_catalog.branch_create(text) FROM PUBLIC;
CREATE TABLE branch_native.objects(catalog oid NOT NULL, object oid NOT NULL, owner bigint NOT NULL, source oid NOT NULL, PRIMARY KEY(catalog,object));
REVOKE ALL ON branch_native.objects FROM PUBLIC;
