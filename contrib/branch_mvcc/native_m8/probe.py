    with cluster.client().connect() as db:assert db.execute('SELECT count(*) AS n FROM "User"')[0]['n']=='1'
    print('PASS: real Prisma migrate dev/shadow and reset preserve main',flush=True)
    django=dict(environment,DATABASE_URL=url)
    run([sys.executable,'manage.py','migrate','--noinput'],HERE/'django_app',django)
    print('PASS: real Django migrate',flush=True)
    run([sys.executable,'app.py','seed'],HERE/'django_app',django)
    for branch in ('django_a','django_b'):
        with cluster.client().connect() as db:db.execute("SELECT branch_create('"+branch+"')")
    def django_branch(branch):
        branch_parameters=dict(parameters,options='-c branch='+branch)
        branch_url='postgresql://'+quote(user)+'@localhost:58445/postgres?'+urlencode(branch_parameters,quote_via=quote)
        return run([sys.executable,'app.py','branch'],HERE/'django_app',dict(django,DATABASE_URL=branch_url,BRANCH_NAME=branch))
    with ThreadPoolExecutor(max_workers=2) as workers:list(workers.map(django_branch,('django_a','django_b')))
    with cluster.client().connect() as db:assert db.execute("SELECT name FROM tasks_user WHERE email='django@example.test'")[0]['name']=='Inherited'
    parameters['options']='-c branch=django_a'
    reverse_url='postgresql://'+quote(user)+'@localhost:58445/postgres?'+urlencode(parameters,quote_via=quote)
    run([sys.executable,'manage.py','migrate','tasks','0001','--noinput'],HERE/'django_app',dict(django,DATABASE_URL=reverse_url))
    with cluster.client().connect() as db:assert db.execute('SELECT rank FROM tasks_task')[0]['rank']=='0'
    print('PASS: parallel Django ORM sessions and isolated reverse schema migration',flush=True)
    run([sys.executable,'manage.py','migrate','tasks','zero','--noinput'],HERE/'django_app',django)
    print('PASS: real Django reverse migration',flush=True)
